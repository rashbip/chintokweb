let currentLang = 'en'; // Default to English

document.addEventListener("DOMContentLoaded", () => {
  // --- Device Detection Logic ---
  const userAgent = navigator.userAgent.toLowerCase();
  const platform = navigator.platform.toLowerCase();

  // Default: Reset all recommended classes
  const cards = document.querySelectorAll(".download-card");
  cards.forEach((c) => c.classList.remove("recommended"));

  let recId = "card-web"; // Default fallback

  if (/android/.test(userAgent)) {
    recId = "card-android";
  } else if (/win/.test(platform) || /windows/.test(userAgent)) {
    recId = "card-windows";
  } else if (/mac/.test(platform) || /macintosh/.test(userAgent)) {
    recId = "card-mac";
  } else if (/linux/.test(platform) || /linux/.test(userAgent)) {
    recId = "card-linux";
  } else if (/iphone|ipad|ipod/.test(userAgent)) {
      recId = "card-ios";
  }

  // Apple TV or Android TV detection is tricky but let's check basic pointers
  if (/smart-tv|smarttv|googletv|android tv|appletv/i.test(userAgent)) {
      recId = "card-tv";
  }

  // Apply highlight
  const targetCard = document.getElementById(recId);
  if (targetCard) {
    targetCard.classList.add("recommended");
  }

  // --- Hero Mosaic Generation ---
  const mosaicContainer = document.getElementById('hero-mosaic');
  if (mosaicContainer) {
    const images = [
      // 'images/hero_bg/Screenshot1.png',
      // 'images/hero_bg/Screenshot2.png',
      // 'images/hero_bg/Screenshot3.png',
      'images/hero_bg/sample_thumb.jpg',
      'images/hero_bg/sample_thumb2.jpg',
      'images/hero_bg/sample_thumb3.jpg',
      'images/hero_bg/sample_thumb4.jpg',
      'images/hero_bg/sample_thumb5.jpg',
      'images/hero_bg/sample_thumb6.jpg'
    ];

    // Create 4 rows
    for (let r = 0; r < 4; r++) {
      const row = document.createElement('div');
      row.className = `mosaic-row ${r % 2 === 0 ? 'forward' : 'backward'}`;
      
      // Duplicate images to ensure seamless loop
      const rowImages = [...images, ...images, ...images]; 
      
      rowImages.forEach(imgSrc => {
        const item = document.createElement('div');
        item.className = 'mosaic-item';
        item.style.backgroundImage = `url('${imgSrc}')`;
        row.appendChild(item);
      });
      
      mosaicContainer.appendChild(row);
    }
  }

  // --- Theme Logic ---
  const themeToggle = document.getElementById('theme-toggle');
  let currentTheme = localStorage.getItem('theme') || 'system';

  function applyTheme(theme) {
    if (theme === 'system') {
      const isDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
      document.documentElement.setAttribute('data-theme', isDark ? 'dark' : 'light');
    } else {
      document.documentElement.setAttribute('data-theme', theme);
    }
    
    if (themeToggle) {
      const activeTheme = theme === 'system' 
        ? (window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light')
        : theme;
      
      themeToggle.innerHTML = activeTheme === 'dark' 
        ? '<i class="fas fa-moon"></i>' 
        : '<i class="fas fa-sun"></i>';
    }
    localStorage.setItem('theme', theme);
  }

  // Initialize Theme
  applyTheme(currentTheme);

  // Listen for system theme changes if set to system
  window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', () => {
    if (localStorage.getItem('theme') === 'system') {
      applyTheme('system');
    }
  });

  if (themeToggle) {
    themeToggle.addEventListener('click', () => {
      // Rotate: Dark -> Light -> System -> Dark
      if (currentTheme === 'dark') currentTheme = 'light';
      else if (currentTheme === 'light') currentTheme = 'system';
      else currentTheme = 'dark';
      
      applyTheme(currentTheme);
    });
  }

  // --- Translation Logic ---
  const langToggle = document.getElementById('lang-toggle');
  
  function updateLanguage() {
      const t = translations[currentLang];
      
      document.title = t.page_title;
      document.documentElement.lang = currentLang;

      // Update all elements with data-i18n attribute
      document.querySelectorAll('[data-i18n]').forEach(el => {
          const key = el.getAttribute('data-i18n');
          if (t[key]) {
              el.innerHTML = t[key];
          }
      });
      
      // Update button text
      if(langToggle) langToggle.innerHTML = t.lang_btn;
  }

  // Initialize
  updateLanguage();

  if(langToggle) {
      langToggle.addEventListener('click', () => {
          currentLang = currentLang === 'en' ? 'bn' : 'en';
          updateLanguage();
      });
  }
});
